// Build script for patchplayguide.com: writes the static site into docs/ (served by GitHub Pages).
// Usage: npm run build
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SITE, page, renderGuide, renderTool, words, modifiedIso } from './layout.mjs';
import { GUIDES } from './guides/index.mjs';
import { TOOLS } from './tools/index.mjs';
import { home, guidesIndex, STATIC_PAGES, NOT_FOUND, OLD_URLS } from './pages.mjs';

const SRC = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(SRC, '..', 'docs');

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });

function write(p, content) {
  const file = path.join(OUT, p.endsWith('/') ? p + 'index.html' : p);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}
function copyDir(from, to, filter = () => true) {
  fs.mkdirSync(to, { recursive: true });
  for (const f of fs.readdirSync(from)) if (filter(f)) fs.copyFileSync(path.join(from, f), path.join(to, f));
}

// lookup for "read next" links
const META = {};
GUIDES.forEach((g) => { META[g.slug] = { path: `/guides/${g.slug}/`, kicker: g.kicker.replace(/^Guide · /, ''), h1: g.h1.replace(/<[^>]+>/g, '') }; });
TOOLS.forEach((t) => { META[t.slug] = { path: `/tools/${t.slug}/`, kicker: 'Tool', h1: t.short }; });
const lookup = (slug) => { if (!META[slug]) throw new Error('unknown related slug ' + slug); return META[slug]; };

const sitemap = [];
const lastmod = { '/privacy/': '2026-11-04', '/about/': '2026-11-04', '/contact/': '2026-11-04' }; // path -> date of last change
const report = [];

// home (AdSense loader so the CMP appears, but no ad slots)
const h = home({ GUIDES });
write('/', page({ ...h, ads: 'no', loader: true, ld: [{ '@type': 'WebSite', name: SITE.name, url: SITE.origin + '/', inLanguage: 'en-US', publisher: { '@type': 'Organization', name: 'AdStern' } }], crumbs: [['Home', '/']] }));
sitemap.push('/');

const gi = guidesIndex({ GUIDES });
write(gi.path, page({ ...gi, ads: 'no', loader: true }));
sitemap.push(gi.path);

for (const g of GUIDES) {
  write(`/guides/${g.slug}/`, renderGuide(g, lookup));
  sitemap.push(`/guides/${g.slug}/`); lastmod[`/guides/${g.slug}/`] = modifiedIso(g);
  report.push({ path: `/guides/${g.slug}/`, words: words(g.lede + g.sections.join(' ') + g.faq.flat().join(' ')) });
}
for (const t of TOOLS) {
  write(`/tools/${t.slug}/`, renderTool(t, lookup));
  sitemap.push(`/tools/${t.slug}/`); lastmod[`/tools/${t.slug}/`] = modifiedIso(t);
  report.push({ path: `/tools/${t.slug}/`, words: words(t.lede + t.sections.join(' ') + t.faq.flat().join(' ')) });
}
for (const p of STATIC_PAGES) {
  write(p.path, page({ ...p, ads: 'no', loader: p.path === '/about/' })); // legal pages and contact: no advertising
  sitemap.push(p.path);
}
write(NOT_FOUND.path, page({ ...NOT_FOUND, ads: 'no', loader: false, noindex: true, canonical: null }));

for (const [oldUrl, newUrl] of OLD_URLS) {
  write(oldUrl, page({
    path: oldUrl, canonical: SITE.origin + newUrl, refresh: newUrl, noindex: true, ads: 'no', loader: false,
    title: 'This page has moved – Patch Play Guide',
    description: `This address of the old Patch Play Guide site has moved. The content now lives at ${SITE.origin}${newUrl} – you are redirected automatically.`,
    body: `<article class="doc"><h1>This page has moved</h1><p>The new address is <a href="${newUrl}">${SITE.origin}${newUrl}</a>. If you are not redirected automatically, follow the link.</p></article>`
  }));
}

// assets
copyDir(path.join(SRC, 'assets', 'css'), path.join(OUT, 'assets', 'css'));
copyDir(path.join(SRC, 'assets', 'js'), path.join(OUT, 'assets', 'js'));
copyDir(path.join(SRC, 'fonts'), path.join(OUT, 'assets', 'fonts'));
const titles = {};
GUIDES.forEach((g) => { titles[g.slug] = g.h1.replace(/<[^>]+>/g, ''); });
fs.writeFileSync(path.join(OUT, 'assets', 'js', 'guide-titles.js'), `/* generated by src/build.mjs */\nwindow.PPG_GUIDE_TITLES = ${JSON.stringify(titles)};\n`);

fs.writeFileSync(path.join(OUT, 'favicon.svg'), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 40 40"><rect x="1" y="1" width="38" height="38" rx="7" fill="#0E1A24" stroke="#FFC531" stroke-width="2"/><path d="M8 12h10M13 7v10" stroke="#47D98A" stroke-width="3"/><path d="M8 21c1.6-1.8 3.4-1.8 5 0s3.4 1.8 5 0" stroke="#FFC531" stroke-width="2.6" fill="none"/><path d="M8 30h10" stroke="#FF6B7F" stroke-width="3"/><path d="M22 10h10M22 21h10M22 30h8" stroke="#9FB0C0" stroke-width="2"/></svg>\n`);
fs.writeFileSync(path.join(OUT, 'CNAME'), SITE.domain); // as committed on main (no trailing newline)
fs.writeFileSync(path.join(OUT, 'ads.txt'), 'google.com, pub-7811071715414905, DIRECT, f08c47fec0942fa0\n');
fs.writeFileSync(path.join(OUT, 'robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${SITE.origin}/sitemap.xml\n`);
fs.writeFileSync(path.join(OUT, '.nojekyll'), '');
fs.writeFileSync(path.join(OUT, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${sitemap.map((u) => `  <url><loc>${SITE.origin}${u}</loc><lastmod>${lastmod[u] || SITE.reviewedIso}</lastmod></url>`).join('\n')}\n</urlset>\n`);

console.log(`Built ${sitemap.length} indexable pages, ${OLD_URLS.length} redirect pages, 404.`);
for (const r of report) console.log(String(r.words).padStart(5), r.path);
